# 5. STREAMING GENERATOR
# ============================================================

def stream_narrative(
    age,
    gender,
    symptoms,
    duration,
    severity,
    existing_conditions,
    medications,
    notes,
    language,
    api_key=None,
):
    """
    Stream a human-readable medical guidance response.

    Uses ChatOpenAI's .stream() method and yields each
    non-empty content chunk.
    """

    messages = MEDICAL_CHAT_PROMPT.format_messages(
        age=age,
        gender=gender,
        symptoms=symptoms,
        duration=duration,
        severity=severity,
        existing_conditions=existing_conditions,
        medications=medications,
        notes=notes,
        language=language,
        json_schema_instruction=JSON_SCHEMA_INSTRUCTION,
    )

    for chunk in create_llm(api_key).stream(messages):

        if chunk.content:
            yield chunk.content