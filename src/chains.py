# 4. RAW SYSTEM / HUMAN / AI MESSAGE DEMO
# ============================================================

def create_message_demo(patient_information):
    """
    Demonstrate the three basic LangChain message types:

    SystemMessage
    HumanMessage
    AIMessage

    This function does NOT call the OpenAI API.
    It simply demonstrates how a conversation can be represented
    using LangChain message objects.
    """

    system_message = SystemMessage(
        content=SYSTEM_PROMPT
    )

    human_message = HumanMessage(
        content=patient_information
    )

    ai_message = AIMessage(
        content=(
            "This is an example AIMessage. "
            "In the real application, this message will be generated "
            "by ChatOpenAI."
        )
    )

    messages = [
        system_message,
        human_message,
        ai_message,
    ]

    return messages

